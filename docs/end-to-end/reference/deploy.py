"""Put the reviewed policy on the cluster.

    policy generated by c2p, and read by a person
      -> applied to the cluster     (this script, a reference implementation)

A command of its own, and that is the whole point of it. The policy it applies was rendered from
templates an agent wrote, so there is a step between generating and trusting, and a step is
easier to insist on than a flag. What this applies is exactly what was read: the same directory,
unmodified, and this script does not generate anything.

**This is a reference implementation and not part of the C2P library** -- it holds a kubeconfig
and writes to a cluster. `README.md` next to this file says what it does with that access, and
what to look for before running it.
"""

import argparse
import pathlib
import sys
from typing import List

HERE = pathlib.Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[2]
# `docs/end-to-end` has a hyphen in it, so the package beside this file cannot be addressed as a
# dotted path and has to be found this way.
sys.path[:0] = [str(REPO_ROOT), str(HERE)]

from platform_k8s import KubeClient, deploy  # noqa: E402


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('-f', '--policy-dir', type=str, default='out', help='The tree you just read')
    parser.add_argument('--kubeconfig', type=str, default=None)
    parser.add_argument(
        '--context',
        type=str,
        required=True,
        help='kubectl context to act on. Required: this writes to a cluster, and inheriting '
        'current-context is how a run lands on the wrong one',
    )
    parser.add_argument('--kubectl', type=str, default='kubectl')
    return parser.parse_args()


def announce(args) -> None:
    """Say what is about to be written to, and where, before writing anything.

    A Deny policy on the wrong cluster rejects real workloads. The context is named on the
    command line, so this is not a confirmation prompt -- it is the record of which cluster the
    run acted on, printed where the person running it will see it.
    """
    print(f'context: {args.context}')
    if args.kubeconfig != None:
        print(f'kubeconfig: {args.kubeconfig}')


def deletion_command(context: str, files: List[pathlib.Path]) -> str:
    """The command that removes what was just applied, and only that.

    The same enumeration `deploy` applied, named the same way. Not `-R -f <dir>`, which after a
    collection run reaches `assessment-results.json` and `posture.json` as well. And not a label
    selector either: the template contract puts `compliance.oscal/check-id` on every policy C2P
    generates, so `-l compliance.oscal/check-id` matches every C2P policy on the cluster --
    other component definitions, other teams, whatever GitOps put there -- and not the set this
    run applied. A printed command gets pasted, so it has to be the narrow one.
    """
    continuation = ' \\\n    '
    arguments = continuation.join(f'-f {path}' for path in files)
    return f'kubectl --context {context} delete{continuation}{arguments}'


def main():
    args = parse_args()
    announce(args)
    client = KubeClient(kubeconfig=args.kubeconfig, context=args.context, kubectl=args.kubectl)
    files = deploy.deploy(client, args.policy_dir)
    print(f'applied {len(files)} policy document(s) from {args.policy_dir}')
    print(f'\nTo take it off again:\n{deletion_command(args.context, files)}')


if __name__ == '__main__':
    main()
