"""Put the reviewed policy on the cluster.

    policy generated by c2p, and read by a person
      -> applied to the cluster     (this script, a reference implementation)

A command of its own, and that is the whole point of it. The policy it applies was rendered from
templates an agent wrote, so there is a step between generating and trusting, and a step is
easier to insist on than a flag. What this applies is exactly what was read: the same directory,
unmodified, and this script does not generate anything.

**This is a reference implementation and not part of the C2P library** -- it holds a kubeconfig
and writes to a cluster. `README.md` next to this file says what it does with that access, and
what to look for before running it.
"""

import argparse
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
REPO_ROOT = HERE.parents[2]
# `docs/end-to-end` has a hyphen in it, so the package beside this file cannot be addressed as a
# dotted path and has to be found this way.
sys.path[:0] = [str(REPO_ROOT), str(HERE)]

from platform_k8s import KubeClient, deploy  # noqa: E402


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('-f', '--policy-dir', type=str, default='out', help='The tree you just read')
    parser.add_argument('--kubeconfig', type=str, default=None)
    parser.add_argument('--context', type=str, default=None)
    parser.add_argument('--kubectl', type=str, default='kubectl')
    return parser.parse_args()


def main():
    args = parse_args()
    client = KubeClient(kubeconfig=args.kubeconfig, context=args.context, kubectl=args.kubectl)
    files = deploy.deploy(client, args.policy_dir)
    print(f'applied {len(files)} policy document(s) from {args.policy_dir}')
    print('\nTo take it off again: kubectl delete -R -f ' + args.policy_dir)


if __name__ == '__main__':
    main()
